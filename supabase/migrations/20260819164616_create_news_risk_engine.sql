create table if not exists public.news_sources (
  id bigint generated by default as identity primary key,
  name text not null unique,
  source_type text not null check (source_type in ('primary','wire','crypto','research')),
  base_reliability numeric(4,3) not null default 0.800 check (base_reliability >= 0 and base_reliability <= 1),
  url text,
  enabled boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.news_events (
  id bigint generated by default as identity primary key,
  source_id bigint references public.news_sources(id) on delete set null,
  external_id text,
  published_at timestamptz not null,
  title text not null,
  summary text,
  url text,
  category text not null check (category in ('fed','treasury','cpi','macro','etf','regulation','geopolitics','crypto','market_structure','other')),
  market_direction text not null default 'neutral' check (market_direction in ('bullish','bearish','neutral','mixed')),
  impact_score smallint not null default 0 check (impact_score between 0 and 100),
  confidence_score smallint not null default 0 check (confidence_score between 0 and 100),
  relevance_score smallint not null default 0 check (relevance_score between 0 and 100),
  btc_impact_score smallint not null default 0 check (btc_impact_score between -100 and 100),
  horizon text not null default 'intraday' check (horizon in ('intraday','short_term','medium_term')),
  is_market_moving boolean not null default false,
  is_verified boolean not null default false,
  raw_hash text,
  created_at timestamptz not null default now(),
  unique (source_id, external_id)
);

create index if not exists idx_news_events_published_at on public.news_events (published_at desc);
create index if not exists idx_news_events_market_moving on public.news_events (is_market_moving, published_at desc);
create index if not exists idx_news_events_category on public.news_events (category, published_at desc);

alter table public.news_sources enable row level security;
alter table public.news_events enable row level security;

create policy "public can read enabled news sources" on public.news_sources
  for select to anon, authenticated using (enabled = true);

create policy "public can read market moving news" on public.news_events
  for select to anon, authenticated using (is_market_moving = true);

